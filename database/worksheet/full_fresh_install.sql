CREATE TABLE customer_kyc (
  kyc_id NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_customer_kyc PRIMARY KEY,
  customer_id NUMBER NOT NULL CONSTRAINT fk_kyc_customer REFERENCES customers(customer_id),
  document_type VARCHAR2(40),
  document_reference VARCHAR2(100),
  status VARCHAR2(12) DEFAULT 'PENDING' NOT NULL CONSTRAINT ck_kyc_status CHECK (status IN ('PENDING','VERIFIED','REJECTED')),
  submitted_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  reviewed_by NUMBER CONSTRAINT fk_kyc_reviewer REFERENCES users(user_id),
