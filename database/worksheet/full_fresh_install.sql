CREATE TABLE deposit_schemes (
  scheme_id NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_deposit_schemes PRIMARY KEY,
  scheme_code VARCHAR2(20) NOT NULL CONSTRAINT uk_deposit_scheme_code UNIQUE,
  scheme_name VARCHAR2(100) NOT NULL CONSTRAINT uk_deposit_scheme_name UNIQUE,
  scheme_type VARCHAR2(30) NOT NULL CONSTRAINT ck_deposit_scheme_type CHECK (scheme_type IN ('FIXED_DEPOSIT','MONTHLY_PROFIT','DPS','SAVINGS_PROFIT','SENIOR_CITIZEN','STUDENT_SAVINGS')),
  minimum_amount NUMBER(15,2) NOT NULL CONSTRAINT ck_deposit_scheme_min CHECK (minimum_amount > 0),
  maximum_amount NUMBER(15,2),
  minimum_months NUMBER NOT NULL,
  maximum_months NUMBER NOT NULL,
  annual_profit_rate NUMBER(7,4) NOT NULL CONSTRAINT ck_deposit_scheme_rate CHECK (annual_profit_rate >= 0 AND annual_profit_rate <= 100),
  calculation_method VARCHAR2(20) DEFAULT 'SIMPLE' NOT NULL CONSTRAINT ck_deposit_scheme_method CHECK (calculation_method IN ('SIMPLE','MONTHLY_COMPOUND')),
  payment_frequency VARCHAR2(20) DEFAULT 'AT_MATURITY' NOT NULL CONSTRAINT ck_deposit_scheme_frequency CHECK (payment_frequency IN ('AT_MATURITY','MONTHLY','RECURRING')),
  tax_percentage NUMBER(5,2) DEFAULT 0 NOT NULL CONSTRAINT ck_deposit_scheme_tax CHECK (tax_percentage BETWEEN 0 AND 100),
  early_withdrawal_rate NUMBER(7,4),
  senior_only CHAR(1) DEFAULT 'N' NOT NULL CONSTRAINT ck_deposit_scheme_senior CHECK (senior_only IN ('Y','N')),
  student_only CHAR(1) DEFAULT 'N' NOT NULL CONSTRAINT ck_deposit_scheme_student CHECK (student_only IN ('Y','N')),
  status VARCHAR2(12) DEFAULT 'ACTIVE' NOT NULL CONSTRAINT ck_deposit_scheme_status CHECK (status IN ('ACTIVE','INACTIVE')),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_deposit_scheme_months CHECK (minimum_months > 0 AND maximum_months >= minimum_months),
  CONSTRAINT ck_deposit_scheme_max CHECK (maximum_amount IS NULL OR maximum_amount >= minimum_amount)
);

